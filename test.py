def check(ok, msg):
    global checks
    checks += 1
    if not ok:
        failures.append(msg)


geo = hou.node("/obj").createNode("geo", "test")
node = geo.createNode("gcode::import::1.0", "gcode")
nozzle_out = geo.createNode("null", "nozzle")
nozzle_out.setInput(0, node, 1)
DEFAULTS = dict(geometry=0, divisions=3, polysoup=1, travel=0, custom=0, arctol=0.01, yup=0,
                origin=0, scale=1.0, colour=0, progress=1.0)


def write(name, text):
    path = os.path.join(tmp, name)
    with open(path, "w") as f:
        f.write(text)
    return path


def load(path, **parms):
    values = dict(DEFAULTS, **parms)
    node.parm("file").set(path)
    for name, value in values.items():
        node.parm(name).set(value)
    node.cook(force=True)
    return node.geometry().freeze()


def nozzle():
    nozzle_out.cook(force=True)
    return nozzle_out.geometry().freeze()


def e_for(width, height, length, flow=1.0, fil=FIL):
    """Filament for a bead of this size, the slicers' way."""
    return height * (width - height * K) * length * flow / fil


def curves(g, feature=None):
    out = []
    for prim in g.prims():
        if feature is None or prim.attribValue("feature") == feature:
            out.append(prim)
    return out


def points_of(prim):
    return [v.point() for v in prim.vertices()]


def close(a, b, tol):
    return abs(a - b) <= tol


