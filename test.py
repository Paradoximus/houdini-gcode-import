def plan_distance(p, path):
    best = math.inf
    for a, b in zip(path, path[1:]):
        a, b, q = V((a[0], a[1], 0)), V((b[0], b[1], 0)), V((p[0], p[1], 0))
        ab = b - a
        s = 0.0 if ab.length() == 0 else max(0.0, min(1.0, (q - a).dot(ab) / ab.dot(ab)))
        best = min(best, (a + ab * s - q).length())
    return best


