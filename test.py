    check(g.findPointAttrib("ptrow") is None and g.findPointAttrib("curvenum") is None,
          "tubes: sweep helper attributes left")
    if not soups:
        check(flipped(g) == 0, f"tubes: {flipped(g)} faces wound against their normals")
