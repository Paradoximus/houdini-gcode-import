def on_circle(prim, centre, radius, tol):
    return max(abs(math.hypot(p.position()[0] - centre[0], p.position()[1] - centre[1]) - radius)
               for p in points_of(prim)) <= tol


def turning(prim, centre):
    """Total signed angle swept around the centre (CCW positive)."""
    total = 0.0
    pts = [p.position() for p in points_of(prim)]
    for a, b in zip(pts, pts[1:]):
        a0 = math.atan2(a[1] - centre[1], a[0] - centre[0])
        a1 = math.atan2(b[1] - centre[1], b[0] - centre[0])
        total += (a1 - a0 + math.pi) % (2 * math.pi) - math.pi
    return total


